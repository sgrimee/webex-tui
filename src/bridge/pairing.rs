//! Explicit, non-UI bootstrap for the paired local bridge session.
//!
//! This module owns no Keychain implementation, terminal prompt, App state or
//! background work. Callers inject a secret store, random source and local
//! bridge pairing backend. The secret is kept only in this orchestration call,
//! is never exposed through [`PairingState`], and is borrowed directly by
//! [`SessionLifecycle`] when opening the session.

use super::session::{
    SessionBackend, SessionClock, SessionFailure, SessionLifecycle, SubscriptionId,
};
use base64::{engine::general_purpose::URL_SAFE_NO_PAD, Engine};
use sha2::{Digest, Sha256};
use std::future::Future;
use webex_bridge::{
    client::{BridgeClient, ClientError},
    dto,
};

/// The bridge API revision understood by this bounded bootstrap seam.
pub(crate) const SUPPORTED_API_VERSION: u32 = 1;

/// An encoded 256-bit D19 pairing secret.
///
/// This intentionally has no `Clone` or `Debug` implementation. The only
/// operations exposed are persistence validation, a borrowed session input and
/// construction of the daemon's hash request.
pub(crate) struct UiSecret(String);

impl UiSecret {
    fn from_random(bytes: [u8; 32]) -> Self {
        Self(URL_SAFE_NO_PAD.encode(bytes))
    }

    /// Validate a canonical secret loaded from the future TUI-only secret store.
    pub(crate) fn from_persisted(value: String) -> Result<Self, SecretStoreFailure> {
        let bytes = URL_SAFE_NO_PAD
            .decode(value.as_bytes())
            .map_err(|_| SecretStoreFailure::Unavailable)?;
        if bytes.len() != 32 || URL_SAFE_NO_PAD.encode(&bytes) != value {
            return Err(SecretStoreFailure::Unavailable);
        }
        Ok(Self(value))
    }

    fn as_str(&self) -> &str {
        &self.0
    }

    /// D19's exact request format: SHA-256 over the encoded secret, then
    /// URL-safe base64 without padding.
    fn pair_hash(&self) -> String {
        URL_SAFE_NO_PAD.encode(Sha256::digest(self.0.as_bytes()))
    }
}

/// Secret-store errors never contain the secret or a backend error string.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) enum SecretStoreFailure {
    Denied,
    Unavailable,
}

/// Random-source errors never contain generated bytes.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) enum RandomFailure {
    Unavailable,
}

/// Local bridge status/pairing failures, intentionally without remote bodies.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) enum PairingBackendFailure {
    Denied,
    Unavailable,
}

/// TUI-owned secret persistence. A production implementation will use the
/// TUI's dedicated Keychain item; this seam deliberately supplies none yet.
pub(crate) trait UiSecretStore: Send {
    fn load(&mut self)
        -> impl Future<Output = Result<Option<UiSecret>, SecretStoreFailure>> + Send;
    fn persist(
        &mut self,
        secret: &UiSecret,
    ) -> impl Future<Output = Result<(), SecretStoreFailure>> + Send;
}

/// Source of exactly 256 random bits for a newly missing pairing secret.
pub(crate) trait RandomSource: Send {
    fn fill_256(&mut self, bytes: &mut [u8; 32]) -> Result<(), RandomFailure>;
}

/// Bounded local API calls needed before a secret reaches a UI session.
pub(crate) trait PairingBackend: Send {
    fn status(&mut self) -> impl Future<Output = Result<u32, PairingBackendFailure>> + Send;
    fn pair(
        &mut self,
        secret_hash: &str,
    ) -> impl Future<Output = Result<(), PairingBackendFailure>> + Send;
}

/// Concrete protected-UDS pairing adapter. It creates no sessions and does not
/// retain a secret; production Keychain/random wiring remains intentionally out
/// of scope for this source-only seam.
pub(crate) struct BridgePairingBackend {
    bridge: BridgeClient,
}

impl BridgePairingBackend {
    pub(crate) fn new(bridge: BridgeClient) -> Self {
        Self { bridge }
    }
}

fn status_failure(_: ClientError) -> PairingBackendFailure {
    PairingBackendFailure::Unavailable
}

fn pair_failure(error: ClientError) -> PairingBackendFailure {
    match error {
        ClientError::Api { status, .. } if status.as_u16() == 403 => PairingBackendFailure::Denied,
        _ => PairingBackendFailure::Unavailable,
    }
}

impl PairingBackend for BridgePairingBackend {
    async fn status(&mut self) -> Result<u32, PairingBackendFailure> {
        self.bridge
            .status()
            .await
            .map(|status: dto::Status| status.api_version)
            .map_err(status_failure)
    }

    async fn pair(&mut self, secret_hash: &str) -> Result<(), PairingBackendFailure> {
        self.bridge.pair_ui(secret_hash).await.map_err(pair_failure)
    }
}

/// Secret-free state observable by a future non-terminal coordinator.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) enum PairingState {
    Idle,
    CheckingStatus,
    LoadingSecret,
    GeneratingSecret,
    PersistingSecret,
    Pairing,
    Connecting,
    Ready,
    Failed(BootstrapFailure),
}

/// Fail-closed bootstrap outcome. No variant contains a UI secret, hash,
/// response body, socket path or presentation configuration.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) enum BootstrapFailure {
    StatusUnavailable,
    VersionMismatch,
    SecretDenied,
    SecretUnavailable,
    RandomUnavailable,
    PersistDenied,
    PersistUnavailable,
    PairDenied,
    PairUnavailable,
    Session(SessionFailure),
}

/// Status-gated orchestration of local secret reuse/creation and explicit D19
/// pairing. It is a state machine only: no terminal, App, startup task or
/// presentation configuration is touched.
pub(crate) struct PairingBootstrap<S: UiSecretStore, P: PairingBackend, R: RandomSource> {
    store: S,
    backend: P,
    random: R,
    state: PairingState,
}

impl<S: UiSecretStore, P: PairingBackend, R: RandomSource> PairingBootstrap<S, P, R> {
    pub(crate) fn new(store: S, backend: P, random: R) -> Self {
        Self {
            store,
            backend,
            random,
            state: PairingState::Idle,
        }
    }

    pub(crate) fn state(&self) -> PairingState {
        self.state
    }

    fn fail<T>(&mut self, failure: BootstrapFailure) -> Result<T, BootstrapFailure> {
        self.state = PairingState::Failed(failure);
        Err(failure)
    }

    /// Check bridge compatibility before any store/random/pair/session work,
    /// pair the existing or freshly persisted secret, then borrow it for one
    /// explicit `SessionLifecycle::connect` call. The bootstrap retains no
    /// secret after this future completes.
    pub(crate) async fn connect<B: SessionBackend, C: SessionClock>(
        &mut self,
        session: &mut SessionLifecycle<B, C>,
    ) -> Result<SubscriptionId, BootstrapFailure> {
        self.state = PairingState::CheckingStatus;
        let version = match self.backend.status().await {
            Ok(version) => version,
            Err(_) => return self.fail(BootstrapFailure::StatusUnavailable),
        };
        if version != SUPPORTED_API_VERSION {
            return self.fail(BootstrapFailure::VersionMismatch);
        }

        self.state = PairingState::LoadingSecret;
        let secret = match self.store.load().await {
            Ok(Some(secret)) => secret,
            Ok(None) => {
                self.state = PairingState::GeneratingSecret;
                let mut bytes = [0_u8; 32];
                if self.random.fill_256(&mut bytes).is_err() {
                    return self.fail(BootstrapFailure::RandomUnavailable);
                }
                let secret = UiSecret::from_random(bytes);
                self.state = PairingState::PersistingSecret;
                match self.store.persist(&secret).await {
                    Ok(()) => secret,
                    Err(SecretStoreFailure::Denied) => {
                        return self.fail(BootstrapFailure::PersistDenied)
                    }
                    Err(SecretStoreFailure::Unavailable) => {
                        return self.fail(BootstrapFailure::PersistUnavailable)
                    }
                }
            }
            Err(SecretStoreFailure::Denied) => return self.fail(BootstrapFailure::SecretDenied),
            Err(SecretStoreFailure::Unavailable) => {
                return self.fail(BootstrapFailure::SecretUnavailable)
            }
        };

        self.state = PairingState::Pairing;
        let secret_hash = secret.pair_hash();
        match self.backend.pair(&secret_hash).await {
            Ok(()) => {}
            Err(PairingBackendFailure::Denied) => return self.fail(BootstrapFailure::PairDenied),
            Err(PairingBackendFailure::Unavailable) => {
                return self.fail(BootstrapFailure::PairUnavailable)
            }
        }

        self.state = PairingState::Connecting;
        let subscription = match session.connect(secret.as_str()).await {
            Ok(subscription) => subscription,
            Err(error) => return self.fail(BootstrapFailure::Session(error)),
        };
        self.state = PairingState::Ready;
        Ok(subscription)
    }
}

